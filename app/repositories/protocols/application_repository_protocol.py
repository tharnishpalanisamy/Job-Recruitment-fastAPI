from typing import Protocol


class ApplicationRepositoryProtocol(Protocol):
    async def create(self, application): ...

    async def get_all_by_job_seeker_id(self, id): ...

    async def get_existing_application(self, job_seeker_id, job_id): ...

    async def get_all(self, recruiter_id, job_id, limit, offset): ...

    async def get_by_application_id(self, id): ...

    async def update_status(self, id, status): ...

    async def delete_by_id(self, id: int) -> None: ...
